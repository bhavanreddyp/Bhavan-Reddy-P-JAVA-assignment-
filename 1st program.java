public class Main {
    public static void main(String[] args) {
        // Use 'long' because the population exceeds the range of standard 32-bit integer (int)
        long indiaPopulation = 1428627663L;
        long chinaPopulation = 1411750000L;

        // Print the stored populations
        System.out.println("Population of India: " + indiaPopulation);
        System.out.println("Population of China: " + chinaPopulation);
    }
}
